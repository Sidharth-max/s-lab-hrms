export type IconType = ComponentType<IconProps>;

/** Same icon with our default stroke (1.75 reads lighter and more "corporate" than Tabler's 2). */
function s(Icon: TablerIcon): IconType {
  const Wrapped = (p: IconProps) => createElement(Icon, { strokeWidth: 1.75, ...p });
  Wrapped.displayName = Icon.displayName;
  return Wrapped;
}

